"""Generate the C header from the deliberately restricted exported Rust signatures."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
source = (root / "src/lib.rs").read_text(encoding="utf-8")
types = {
    "u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t",
    "u64": "uint64_t", "i32": "int32_t", "i64": "int64_t",
    "usize": "size_t", "McStatus": "McStatus", "McProgress": "McProgress",
    "*const c_char": "const char *", "*const u8": "const uint8_t *",
    "*mut c_void": "void *", "*mut McBuffer": "McBuffer *",
    "*mut McConnection": "McConnection *", "*mut *mut McConnection": "McConnection **",
}
lines = ["""/* Generated by tools/generate_header.py. Do not edit.
 * All strings are UTF-8. All pointers must be valid for their documented lifetime.
 * Buffers are not NUL terminated. See README.md for ownership and threading.
 */
#ifndef MCUMGR_H
#define MCUMGR_H
#include <stddef.h>
#include <stdint.h>
#ifdef _WIN32
#define MC_CALL __cdecl
#else
#define MC_CALL
#endif
#ifdef __cplusplus
extern "C" {
#endif
typedef int32_t McStatus;
#define MC_OK 0
#define MC_INVALID_ARGUMENT 1
#define MC_OPERATION_FAILED 2
#define MC_PANIC 3
typedef struct McConnection McConnection;
typedef struct McBuffer { uint8_t *data; size_t len; } McBuffer;
typedef void (MC_CALL *McProgress)(uint64_t offset, uint64_t total, void *user);
"""]
exports = re.findall(r'((?:///[^\n]*\n)*)#\[no_mangle\]\npub unsafe extern "C" fn (\w+)\(([^)]*)\) -> (\w+)', source)
if not exports or len(exports) != source.count("#[no_mangle]"):
    raise RuntimeError("An export has an unsupported signature; update the header generator")
for docs, name, args, result in exports:
    if docs:
        lines.append("/* " + " ".join(line[4:] for line in docs.strip().splitlines()) + " */")
    cargs = []
    for arg in args.split(","):
        if not arg.strip():
            continue
        key, typ = arg.strip().split(": ", 1)
        cargs.append(types[typ] + " " + key)
    lines.append(types[result] + " MC_CALL " + name + "(" + (", ".join(cargs) or "void") + ");")
    lines.append("")
lines.append("""#ifdef __cplusplus
}
#endif
#endif
""")
header = "\n".join(lines)
target = root / "include/mcumgr.h"
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != header:
        raise SystemExit("Header is stale: run python ffi/tools/generate_header.py")
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(header, encoding="utf-8", newline="\n")
